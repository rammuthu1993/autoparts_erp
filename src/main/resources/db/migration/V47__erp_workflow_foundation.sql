-- ERP workflow foundation: units, product price history, return inspection,
-- credit-note linkage, cash reconciliation metadata and request idempotency.
-- Existing product.unit remains text for backward compatibility; new UI can
-- populate it from the active unit master without a breaking column migration.

CREATE TABLE IF NOT EXISTS units (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid UUID NOT NULL UNIQUE DEFAULT gen_random_uuid(),
    unit_code VARCHAR(30) NOT NULL UNIQUE,
    unit_name VARCHAR(80) NOT NULL,
    symbol VARCHAR(20) NOT NULL,
    decimal_allowed BOOLEAN NOT NULL DEFAULT TRUE,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

INSERT INTO units (unit_code, unit_name, symbol, decimal_allowed)
VALUES
 ('PCS', 'Pieces', 'pcs', FALSE),
 ('SET', 'Set', 'set', FALSE),
 ('BOX', 'Box', 'box', FALSE),
 ('PAIR', 'Pair', 'pair', FALSE),
 ('KG', 'Kilogram', 'kg', TRUE),
 ('G', 'Gram', 'g', TRUE),
 ('L', 'Litre', 'L', TRUE),
 ('ML', 'Millilitre', 'ml', TRUE),
 ('M', 'Metre', 'm', TRUE)
ON CONFLICT (unit_code) DO NOTHING;

CREATE TABLE IF NOT EXISTS product_price_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(id),
    purchase_price NUMERIC(14,2) NOT NULL,
    selling_price NUMERIC(14,2) NOT NULL,
    effective_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    changed_by BIGINT,
    change_source VARCHAR(30) NOT NULL DEFAULT 'PRODUCT_UPDATE'
);
CREATE INDEX IF NOT EXISTS idx_product_price_history_product_effective
    ON product_price_history(product_id, effective_at DESC);

CREATE OR REPLACE FUNCTION record_product_price_history()
RETURNS TRIGGER AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO product_price_history(product_id, purchase_price, selling_price, change_source)
        VALUES (NEW.id, NEW.purchase_price, NEW.selling_price, 'PRODUCT_CREATE');
    ELSIF NEW.purchase_price IS DISTINCT FROM OLD.purchase_price
       OR NEW.selling_price IS DISTINCT FROM OLD.selling_price THEN
        INSERT INTO product_price_history(product_id, purchase_price, selling_price, change_source)
        VALUES (NEW.id, NEW.purchase_price, NEW.selling_price, 'PRODUCT_UPDATE');
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_product_price_history ON products;
CREATE TRIGGER trg_product_price_history
AFTER INSERT OR UPDATE OF purchase_price, selling_price ON products
FOR EACH ROW EXECUTE FUNCTION record_product_price_history();

-- Return inspection is additive. Existing ACCEPTED return behaviour remains
-- compatible; future inspection actions can populate these columns.
ALTER TABLE sales_returns
    ADD COLUMN IF NOT EXISTS inspection_status VARCHAR(20) NOT NULL DEFAULT 'NOT_REQUIRED',
    ADD COLUMN IF NOT EXISTS inspection_note VARCHAR(1000),
    ADD COLUMN IF NOT EXISTS inspected_by BIGINT,
    ADD COLUMN IF NOT EXISTS inspected_at TIMESTAMPTZ;

ALTER TABLE sales_return_products
    ADD COLUMN IF NOT EXISTS disposition VARCHAR(30) NOT NULL DEFAULT 'RESTOCK';

-- Persisted external-reference/idempotency registry. Scope is the operation
-- and key; response body is deliberately not stored in this foundation patch.
CREATE TABLE IF NOT EXISTS api_idempotency_keys (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_scope VARCHAR(120) NOT NULL,
    idempotency_key VARCHAR(150) NOT NULL,
    request_hash VARCHAR(128) NOT NULL,
    resource_uuid UUID,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_api_idempotency_scope_key UNIQUE(operation_scope, idempotency_key)
);

-- Cash reconciliation metadata, nullable for compatibility with old sessions.
ALTER TABLE cash_register_sessions
    ADD COLUMN IF NOT EXISTS closing_notes VARCHAR(1000),
    ADD COLUMN IF NOT EXISTS discrepancy_reason VARCHAR(500),
    ADD COLUMN IF NOT EXISTS denomination_count JSONB;
